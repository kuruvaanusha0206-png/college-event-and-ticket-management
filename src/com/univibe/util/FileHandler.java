package com.univibe.util;

import com.univibe.model.Ticket;

import java.io.*;
import java.text.SimpleDateFormat;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;

/**
 * File I/O Management Utility.
 * Demonstrates:
 *  1. File Handling (File, FileWriter, BufferedWriter, PrintWriter, BufferedReader, FileReader)
 *  2. Try-with-resources for automatic resource closing
 *  3. Directory creation and path handling
 *  4. Logging and Audit Trail generation
 *  5. Exporting printable digital tickets and CSV reports
 */
public final class FileHandler {

    private static final String TICKETS_DIR = "tickets";
    private static final String REPORTS_DIR = "reports";
    private static final String LOGS_DIR = "logs";
    private static final String AUDIT_LOG_FILE = "logs/univibe_audit.log";

    private FileHandler() {}

    static {
        // Ensure directories exist on startup
        ensureDirectoryExists(TICKETS_DIR);
        ensureDirectoryExists(REPORTS_DIR);
        ensureDirectoryExists(LOGS_DIR);
    }

    private static void ensureDirectoryExists(String path) {
        File dir = new File(path);
        if (!dir.exists()) {
            boolean created = dir.mkdirs();
            if (created) {
                System.out.println("[FileHandler] Created directory: " + path);
            }
        }
    }

    /**
     * Saves a digital ticket admit pass to a formatted text file on disk.
     */
    public static File saveTicketToFile(Ticket ticket) throws IOException {
        if (ticket == null) {
            throw new IllegalArgumentException("Ticket cannot be null");
        }

        ensureDirectoryExists(TICKETS_DIR);
        String safeName = ticket.getTicketCode().replaceAll("[^a-zA-Z0-9_-]", "_");
        File file = new File(TICKETS_DIR, safeName + ".txt");

        boolean[][] matrix = QRMatrixGenerator.generateMatrix(ticket.getTicketCode() + "#" + ticket.getQrHash());
        String asciiQR = QRMatrixGenerator.toAsciiArt(matrix);

        try (PrintWriter writer = new PrintWriter(new BufferedWriter(new FileWriter(file)))) {
            writer.println(ticket.generatePrintableContent());
            writer.println(" DIGITAL QR VERIFICATION PATTERN:");
            writer.print(asciiQR);
            writer.println("\n [Generated by UniVibe Campus Pass System]");
        }

        logAuditActivity("TICKET_EXPORT", "SYSTEM", "Exported ticket file: " + file.getAbsolutePath());
        return file;
    }

    /**
     * Exports tabular report content (CSV or TXT) to the reports directory.
     */
    public static File exportReportToFile(String reportContent, String filename) throws IOException {
        ensureDirectoryExists(REPORTS_DIR);
        File file = new File(REPORTS_DIR, filename);

        try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
            writer.write(reportContent);
        }

        logAuditActivity("REPORT_EXPORT", "SYSTEM", "Generated report: " + file.getAbsolutePath());
        return file;
    }

    /**
     * Appends an audit activity entry to the central audit log file.
     */
    public static synchronized void logAuditActivity(String action, String actor, String message) {
        ensureDirectoryExists(LOGS_DIR);
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss.SSS");
        String timestamp = sdf.format(new Date());

        String logEntry = String.format("[%s] [%s] [%s] %s%n", timestamp, action, actor, message);

        try (FileWriter fw = new FileWriter(AUDIT_LOG_FILE, true);
             BufferedWriter bw = new BufferedWriter(fw)) {
            bw.write(logEntry);
        } catch (IOException e) {
            System.err.println("[FileHandler] Failed to append to audit log: " + e.getMessage());
        }
    }

    /**
     * Reads the most recent lines from the audit log file.
     */
    public static List<String> readRecentAuditLogs(int maxLines) {
        List<String> lines = new ArrayList<>();
        File logFile = new File(AUDIT_LOG_FILE);
        if (!logFile.exists()) {
            return lines;
        }

        try (BufferedReader reader = new BufferedReader(new FileReader(logFile))) {
            String line;
            while ((line = reader.readLine()) != null) {
                lines.add(line);
                if (lines.size() > maxLines) {
                    lines.remove(0); // keep sliding window of recent lines
                }
            }
        } catch (IOException e) {
            System.err.println("[FileHandler] Failed to read audit log: " + e.getMessage());
        }
        return lines;
    }
}
